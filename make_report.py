#!/usr/bin/env python3
"""Generate the results sections of REPORT.md from results/*.csv."""
import csv, glob, statistics as st, sys
from collections import defaultdict
from datetime import datetime

NUMERIC = ["ttft_ms","tpot_ms","observed_interchunk_ms","prompt_tokens","output_tokens",
    "prompt_tps","output_tps","total_request_time_s","ram_start_mb","ram_avg_mb","ram_peak_mb",
    "swap_peak_mb","cpu_avg_percent","cpu_peak_avg_percent","cpu_peak_core_percent",
    "gpu_avg_percent","gpu_peak_percent","cpu_temp_start_c","cpu_temp_peak_c",
    "gpu_temp_start_c","gpu_temp_peak_c","power_avg_w","power_peak_w","estimated_energy_j"]

def num(row, key):
    try:
        v = float(row.get(key))
    except (TypeError, ValueError):
        return None
    return v

def truthy(v):
    return str(v).strip().lower() in ("true", "1", "yes", "y")

def load(paths):
    rows = []
    for p in sorted(paths):
        with open(p, newline="", encoding="utf-8", errors="replace") as f:
            for r in csv.DictReader(f):
                if (r.get("profile") or "").strip().upper() == "TOTAL PROMPT TIME":
                    continue
                if not (r.get("model") or "").strip():
                    continue
                r["_file"] = p
                rows.append(r)
    return rows

def agg(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return None
    m = st.fmean(vals)
    sd = st.stdev(vals) if len(vals) > 1 else 0.0
    return {"n": len(vals), "mean": m, "sd": sd, "median": st.median(vals),
            "min": min(vals), "max": max(vals)}

def cell(a, dp=2, plusminus=True):
    if not a:
        return "n/a"
    if plusminus and a["n"] > 1:
        return f"{a['mean']:.{dp}f} ± {a['sd']:.{dp}f}"
    return f"{a['mean']:.{dp}f}"

def main(argv):
    paths = argv[1:] or sorted(glob.glob("results/*.csv"))
    if not paths:
        sys.exit("No CSVs found. Run from the repo root, or pass paths explicitly.")
    rows = load(paths)
    if not rows:
        sys.exit("CSVs contained no benchmark rows.")

    models = []
    for r in rows:
        m = r["model"].strip()
        if m not in models:
            models.append(m)

    out = []
    w = out.append
    w("<!-- Generated by make_report.py -->")
    w("")
    w(f"Data files: {len(paths)} CSV(s) · {len(rows)} benchmark rows · "
      f"generated {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    w("")

    # ---------- headline table ----------
    w("## Headline results")
    w("")
    w("| Model | Quant | Runs | Completed | Truncated | Output tok/s | TTFT (ms) | TPOT (ms) | Avg power (W) | J / output token | Peak RAM (MB) | Peak CPU °C |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for m in models:
        rs = [r for r in rows if r["model"].strip() == m]
        done = [r for r in rs if truthy(r.get("completed"))]
        trunc = sum(1 for r in rs if truthy(r.get("truncated")))
        quant = next((r.get("quantization") for r in rs if r.get("quantization")), "n/a")
        tps = agg([num(r, "output_tps") for r in done])
        ttft = agg([num(r, "ttft_ms") for r in done])
        tpot = agg([num(r, "tpot_ms") for r in done])
        pwr = agg([num(r, "power_avg_w") for r in rs])
        jtok = agg([num(r, "estimated_energy_j") / num(r, "output_tokens")
                    for r in done if num(r, "output_tokens") and num(r, "estimated_energy_j")])
        ram = agg([num(r, "ram_peak_mb") for r in rs])
        temp = agg([num(r, "cpu_temp_peak_c") for r in rs])
        w(f"| {m} | {quant} | {len(rs)} | {len(done)} | {trunc} | {cell(tps)} | {cell(ttft,0)} | "
          f"{cell(tpot)} | {cell(pwr)} | {cell(jtok,3)} | {cell(ram,0)} | {cell(temp,1)} |")
    w("")

    # ---------- per-profile table ----------
    for m in models:
        w(f"### {m} — by profile")
        w("")
        w("| Profile | Thinking | Runs | Output tok/s | TTFT (ms) | TPOT (ms) | Output tokens | Truncated |")
        w("|---|---|---|---|---|---|---|---|")
        profs = []
        for r in rows:
            if r["model"].strip() == m and r.get("profile") not in profs:
                profs.append(r.get("profile"))
        for p in profs:
            rs = [r for r in rows if r["model"].strip() == m and r.get("profile") == p]
            done = [r for r in rs if truthy(r.get("completed"))]
            think = "yes" if any(truthy(r.get("thinking")) for r in rs) else "no"
            w(f"| {p} | {think} | {len(rs)} | {cell(agg([num(r,'output_tps') for r in done]))} | "
              f"{cell(agg([num(r,'ttft_ms') for r in done]),0)} | "
              f"{cell(agg([num(r,'tpot_ms') for r in done]))} | "
              f"{cell(agg([num(r,'output_tokens') for r in done]),0,False)} | "
              f"{sum(1 for r in rs if truthy(r.get('truncated')))} |")
        w("")

    # ---------- failures ----------
    bad = [r for r in rows if not truthy(r.get("completed")) or (r.get("error") or "").strip()]
    w("## Failed or incomplete runs")
    w("")
    if bad:
        w("| Model | Profile | Prompt | Status | Error |")
        w("|---|---|---|---|---|")
        for r in bad:
            err = (r.get("error") or "").replace("|", "/")[:120] or "-"
            w(f"| {r['model']} | {r.get('profile')} | {r.get('prompt_id')} | {r.get('status')} | {err} |")
    else:
        w("None. Every row reported `completed=true` with no error string.")
    w("")

    # ---------- run order / thermal context ----------
    w("## Run order and thermal context")
    w("")
    w("| File | Model | Rows | First run (UTC) | Last run (UTC) | Temp start → peak (°C) |")
    w("|---|---|---|---|---|---|")
    by_file = defaultdict(list)
    for r in rows:
        by_file[r["_file"]].append(r)
    for f, rs in sorted(by_file.items()):
        ts = sorted(r.get("timestamp_utc") or "" for r in rs)
        t0 = agg([num(r, "cpu_temp_start_c") for r in rs])
        t1 = agg([num(r, "cpu_temp_peak_c") for r in rs])
        trend = f"{cell(t0,1,False)} → {cell(t1,1,False)}" if t0 and t1 else "n/a"
        w(f"| {f.split('/')[-1]} | {rs[0]['model'].strip()} | {len(rs)} | {ts[0][:19]} | "
          f"{ts[-1][:19]} | {trend} |")
    w("")

    text = "\n".join(out)
    with open("results/report_tables.md", "w", encoding="utf-8") as f:
        f.write(text + "\n")
    print(text)
    print(f"\nWritten to results/report_tables.md ({len(text)} chars)")

if __name__ == "__main__":
    main(sys.argv)
